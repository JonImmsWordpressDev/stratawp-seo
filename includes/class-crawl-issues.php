	/**
	 * Return issue counts grouped by severity for the given run.
	 *
	 * @param int $run_id Target run ID.
	 * @return array{error:int,warning:int,notice:int}
	 */
	public static function severity_counts( int $run_id ): array {
		global $wpdb;

		$table = $wpdb->prefix . self::TABLE_ISSUES;

		// phpcs:disable WordPress.DB.DirectDatabaseQuery.DirectQuery,WordPress.DB.DirectDatabaseQuery.NoCaching,WordPress.DB.PreparedSQL.InterpolatedNotPrepared
		$rows = (array) $wpdb->get_results(
			$wpdb->prepare(
				"SELECT severity, COUNT(*) AS cnt FROM {$table} WHERE run_id = %d GROUP BY severity",
				$run_id
			),
			ARRAY_A
		);
		// phpcs:enable WordPress.DB.DirectDatabaseQuery.DirectQuery,WordPress.DB.DirectDatabaseQuery.NoCaching,WordPress.DB.PreparedSQL.InterpolatedNotPrepared

		$counts = array(
			'error'   => 0,
			'warning' => 0,
			'notice'  => 0,
		);
		foreach ( $rows as $row ) {
			$severity = (string) ( $row['severity'] ?? '' );
			if ( isset( $counts[ $severity ] ) ) {
				$counts[ $severity ] = (int) $row['cnt'];
			}
		}

		return $counts;
	}

	/**
	 * Return all issue rows for a run, detail JSON decoded, grouped by type.
	 *
	 * Each row gains an 'is_new' flag: true when first_seen_run equals the
	 * queried run (i.e. the issue was not present in any earlier run).
	 *
	 * @param int $run_id Target run ID.
	 * @return array<string, array[]> Issue rows keyed by type.
	 */
	public static function issues_for_run( int $run_id ): array {
		global $wpdb;

		$table = $wpdb->prefix . self::TABLE_ISSUES;

		// phpcs:disable WordPress.DB.DirectDatabaseQuery.DirectQuery,WordPress.DB.DirectDatabaseQuery.NoCaching,WordPress.DB.PreparedSQL.InterpolatedNotPrepared
		$rows = (array) $wpdb->get_results(
			$wpdb->prepare(
				"SELECT id, type, url, detail, severity, post_id, object_type, object_id, first_seen_run FROM {$table} WHERE run_id = %d ORDER BY type, id",
				$run_id
			),
			ARRAY_A
		);
		// phpcs:enable WordPress.DB.DirectDatabaseQuery.DirectQuery,WordPress.DB.DirectDatabaseQuery.NoCaching,WordPress.DB.PreparedSQL.InterpolatedNotPrepared

		$grouped = array();
		foreach ( $rows as $row ) {
			$detail                    = json_decode( (string) $row['detail'], true );
			$row['detail']             = is_array( $detail ) ? $detail : array();
			$row['object_type']        = (string) ( $row['object_type'] ?? '' );
			$row['object_id']          = (int) ( $row['object_id'] ?? 0 );
			$row['is_new']             = (int) $row['first_seen_run'] === $run_id;
			$grouped[ $row['type'] ][] = $row;
		}

		return $grouped;
	}

	/**
	 * Stamp an issue row's detail JSON with fixed_at so the dashboard can
	 * render it as resolved-pending-recrawl. The row itself is kept — the
	 * next crawl is the source of truth.
	 *
	 * @param int $issue_id Issue row ID.
	 */
	public static function mark_fixed( int $issue_id ): void {
		global $wpdb;

		$table = $wpdb->prefix . self::TABLE_ISSUES;

		// phpcs:disable WordPress.DB.DirectDatabaseQuery.DirectQuery,WordPress.DB.DirectDatabaseQuery.NoCaching,WordPress.DB.PreparedSQL.InterpolatedNotPrepared
		$raw = $wpdb->get_var( $wpdb->prepare( "SELECT detail FROM {$table} WHERE id = %d", $issue_id ) );
		if ( null === $raw ) {
			return;
		}

		$detail             = is_array( json_decode( (string) $raw, true ) ) ? json_decode( (string) $raw, true ) : array();
		$detail['fixed_at'] = time();

		$wpdb->update(
			$table,
			array( 'detail' => wp_json_encode( $detail ) ),
			array( 'id' => $issue_id ),
			array( '%s' ),
			array( '%d' )
		);
		// phpcs:enable WordPress.DB.DirectDatabaseQuery.DirectQuery,WordPress.DB.DirectDatabaseQuery.NoCaching,WordPress.DB.PreparedSQL.InterpolatedNotPrepared
	}

	/**
	 * Return the most recent distinct run IDs, newest first.
	 *
	 * Used by the Site Audit dashboard to locate the previous run (for triage
	 * deltas) and to build the trend strip.
	 *
	 * @param int $limit Maximum number of run IDs to return. Default 5.
	 * @return int[] Run IDs, newest first.
	 */
	public static function latest_run_ids( int $limit = 5 ): array {
		global $wpdb;

		$table = $wpdb->prefix . self::TABLE_QUEUE;

		// phpcs:disable WordPress.DB.DirectDatabaseQuery.DirectQuery,WordPress.DB.DirectDatabaseQuery.NoCaching,WordPress.DB.PreparedSQL.InterpolatedNotPrepared
		$ids = $wpdb->get_col(
			$wpdb->prepare(
				"SELECT DISTINCT run_id FROM {$table} ORDER BY run_id DESC LIMIT %d",
