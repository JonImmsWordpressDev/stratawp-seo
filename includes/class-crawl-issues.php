	// DB SCHEMA
	// =========================================================================

	/**
	 * Create/upgrade the crawl tables when the stored schema version is stale.
	 *
	 * Runs at init so existing installs get the tables on plugin update
	 * without a deactivate/reactivate cycle (SWPS_Bot_Analytics_Tracker
	 * precedent).
	 */
	public static function maybe_upgrade(): void {
		$installed = get_option( self::OPT_DB_VER );
		if ( self::DB_VERSION === $installed ) {
			return;
		}

		// v3 adds a UNIQUE KEY on (run_id, url_hash) to the pages table so
		// insert_page() can REPLACE instead of duplicating on re-processing.
		// Every pre-v3 row has url_hash '' (the column did not exist), which
		// collides across every row of a run once the unique index is added,
		// breaking dbDelta's ALTER TABLE. Page-facts rows are transient,
		// run-scoped audit data — regenerated by the next crawl and already
		// pruned after 5 runs, never referenced outside a run — so clearing
		// them ahead of the migration is safe, and simpler than backfilling
		// (which cannot resolve genuine pre-fix duplicate rows for the same
		// URL within a run anyway, since that duplication is exactly the bug
		// this version fixes).
		if ( $installed && version_compare( (string) $installed, '3', '<' ) ) {
			self::truncate_pre_v3_pages_table();
		}

		self::create_tables();
		update_option( self::OPT_DB_VER, self::DB_VERSION );
	}

	/**
	 * Clear the pages table ahead of the v3 migration, if it already exists.
	 *
	 * Guarded with a table-existence check so installs upgrading from before
	 * the pages table existed at all (DB_VERSION '1') don't error.
	 */
	private static function truncate_pre_v3_pages_table(): void {
		global $wpdb;
		$pages = $wpdb->prefix . self::TABLE_PAGES;
		// phpcs:disable WordPress.DB.DirectDatabaseQuery.DirectQuery,WordPress.DB.DirectDatabaseQuery.NoCaching,WordPress.DB.PreparedSQL.NotPrepared
		$exists = $wpdb->get_var( $wpdb->prepare( 'SHOW TABLES LIKE %s', $pages ) );
		if ( $exists === $pages ) {
			$wpdb->query( "TRUNCATE TABLE {$pages}" );
		}
		// phpcs:enable WordPress.DB.DirectDatabaseQuery.DirectQuery,WordPress.DB.DirectDatabaseQuery.NoCaching,WordPress.DB.PreparedSQL.NotPrepared
	}

	/**
	 * Create or upgrade crawl tables via dbDelta.
	 *
	 * Called on plugin activation and on DB-version mismatch at init.
	 * Safe to call multiple times (dbDelta is idempotent).
	 */
	public static function create_tables(): void {
		global $wpdb;

		$charset = $wpdb->get_charset_collate();
		$queue   = $wpdb->prefix . self::TABLE_QUEUE;
		$issues  = $wpdb->prefix . self::TABLE_ISSUES;
		$pages   = $wpdb->prefix . self::TABLE_PAGES;

		$sql_queue = "CREATE TABLE {$queue} (
			id         BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
			run_id     BIGINT UNSIGNED NOT NULL,
			url_hash   VARCHAR(64)     NOT NULL DEFAULT '',
			url        VARCHAR(2083)   NOT NULL DEFAULT '',
			depth      SMALLINT UNSIGNED NOT NULL DEFAULT 0,
			status     VARCHAR(10)     NOT NULL DEFAULT 'pending',
			found_on   VARCHAR(2083)   NOT NULL DEFAULT '',
			created_at DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP,
			PRIMARY KEY (id),
			UNIQUE KEY idx_run_hash (run_id, url_hash),
			KEY idx_run_status (run_id, status)
		) {$charset};";

		$sql_issues = "CREATE TABLE {$issues} (
			id             BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
			run_id         BIGINT UNSIGNED NOT NULL,
			type           VARCHAR(50)     NOT NULL DEFAULT '',
			url            VARCHAR(2083)   NOT NULL DEFAULT '',
			detail         LONGTEXT        NOT NULL DEFAULT '',
			severity       VARCHAR(10)     NOT NULL DEFAULT 'warning',
			post_id        BIGINT UNSIGNED             DEFAULT NULL,
			object_type    VARCHAR(10)                 DEFAULT NULL,
			object_id      BIGINT UNSIGNED             DEFAULT NULL,
			first_seen_run BIGINT UNSIGNED NOT NULL,
			PRIMARY KEY (id),
			KEY idx_run_id (run_id),
			KEY idx_type   (type)
		) {$charset};";

		$sql_pages = "CREATE TABLE {$pages} (
			id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
			run_id BIGINT UNSIGNED NOT NULL,
			url VARCHAR(500) NOT NULL,
			url_hash CHAR(32) NOT NULL DEFAULT '',
			status_code SMALLINT UNSIGNED NOT NULL DEFAULT 0,
			content_type VARCHAR(100) NOT NULL DEFAULT '',
			title TEXT,
			title_hash CHAR(32) NOT NULL DEFAULT '',
			meta_desc_hash CHAR(32) NOT NULL DEFAULT '',
			desc_length SMALLINT UNSIGNED NOT NULL DEFAULT 0,
			flags INT UNSIGNED NOT NULL DEFAULT 0,
			word_count INT UNSIGNED NOT NULL DEFAULT 0,
			html_bytes INT UNSIGNED NOT NULL DEFAULT 0,
			text_bytes INT UNSIGNED NOT NULL DEFAULT 0,
			h1_count SMALLINT UNSIGNED NOT NULL DEFAULT 0,
			canonical VARCHAR(500) DEFAULT NULL,
			internal_links LONGTEXT,
			unminified_assets TEXT,
			PRIMARY KEY  (id),
			UNIQUE KEY idx_run_urlhash (run_id, url_hash),
			KEY idx_run (run_id),
			KEY idx_run_title (run_id, title_hash),
			KEY idx_run_desc (run_id, meta_desc_hash)
		) {$charset};";

		require_once ABSPATH . 'wp-admin/includes/upgrade.php';
		dbDelta( $sql_queue );
		dbDelta( $sql_issues );
		dbDelta( $sql_pages );
	}

